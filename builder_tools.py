"""Install app-scoped wrappers without relaxing ADK's code-reference guards."""

from pathlib import Path
import json

from shared_tools.registry import ENTRYPOINT_MODULE, entrypoint_groups, list_tools

WRAPPER_FILE = f"{ENTRYPOINT_MODULE}.py"
MANAGED_PREFIX = '''"""Generated from shared_tools.registry; do not edit this file."""
from shared_tools.registry import bind_tools as _bind_tools

_bind_tools(globals(), '''
MANAGED_SUFFIX = ')\ndel _bind_tools\n'

# Exact pre-registry template: only this known source is safe to migrate.
LEGACY_WRAPPER_SOURCE = '''"""Managed entry points for the project's shared DeepSeek web tools."""
from web_tools import deepseek_search as _search, deepseek_fetch as _fetch

async def deepseek_search(query: str, count: int = 5) -> dict:
    return await _search(query, count)

async def deepseek_fetch(url: str) -> dict:
    return await _fetch(url)

deepseek_search.__doc__ = _search.__doc__
deepseek_fetch.__doc__ = _fetch.__doc__
'''


def local_tool_names(app_name: str) -> tuple[str, ...]:
    return tuple(tool.reference(app_name) for tool in list_tools())


def render_entrypoint(names: tuple[str, ...]) -> str:
    return MANAGED_PREFIX + json.dumps(names) + MANAGED_SUFFIX


def _is_managed(source: str) -> bool:
    if not source.startswith(MANAGED_PREFIX) or not source.endswith(MANAGED_SUFFIX):
        return False
    try:
        names = json.loads(source[len(MANAGED_PREFIX):-len(MANAGED_SUFFIX)])
    except ValueError:
        return False
    return isinstance(names, list) and all(isinstance(name, str) and name.isidentifier() for name in names)


def _write_entrypoint(target: Path, source: str) -> None:
    if target.is_symlink():
        raise RuntimeError(f"Refusing symlink for local tool entry: {target}")
    if target.exists():
        existing = target.read_text()
        if existing == source:
            return
        known_legacy = target.name == "deepseek_web_tools.py" and existing == LEGACY_WRAPPER_SOURCE
        if not known_legacy and not _is_managed(existing):
            raise RuntimeError(f"Local tool entry already has custom content: {target}")
        target.write_text(source)
        return
    with target.open("x") as file:
        file.write(source)


def install_registered_tools(root: Path, app_name: str | None = None) -> None:
    root = root.resolve()
    apps = [root / app_name] if app_name else list(root.iterdir())
    for app in apps:
        name = app.name
        if not name.isidentifier() or name.startswith("__") or app.is_symlink() or not app.is_dir():
            continue
        if not app.resolve().is_relative_to(root):
            continue
        # Native draft saving may happen before the first canonical save.
        for directory in (app, app / "tmp" / name):
            if not directory.resolve().is_relative_to(app.resolve()) or not (directory / "root_agent.yaml").is_file():
                continue
            for module, names in entrypoint_groups().items():
                _write_entrypoint(directory / f"{module}.py", render_entrypoint(names))


# Preserve the old launcher integration name for local callers.
install_web_tools = install_registered_tools
